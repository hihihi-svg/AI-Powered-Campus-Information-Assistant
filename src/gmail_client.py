"""
gmail_client.py - Read-only Google Gmail API client wrapper.

Adheres strictly to:
- Read-only scope: https://www.googleapis.com/auth/gmail.readonly
- Google OAuth Web Application flow with local Flask callback server on port 5678
- Callback route: /rest/oauth2-credential/callback
- Redirect URI: http://localhost:5678/rest/oauth2-credential/callback
- Standard google-auth-oauthlib / OAuthlib state verification
- Auto-refresh of expired tokens using refresh token
- Local secrets isolation (secrets/credentials.json, secrets/token.json)
- Zero credentials, tokens, or authorization codes exposed in logs
"""

import json
import logging
import os
import threading
import traceback
import webbrowser
from typing import Any, Dict, List, Optional, Tuple

logger = logging.getLogger("campus_pipeline.gmail_client")

SCOPES = ["https://www.googleapis.com/auth/gmail.readonly"]
REDIRECT_URI = "http://localhost:5678/rest/oauth2-credential/callback"


def run_flask_oauth_flow(
    credentials_path: str = "secrets/credentials.json",
    redirect_uri: str = REDIRECT_URI,
    port: int = 5678,
    timeout_seconds: int = 300,
) -> Any:
    """
    Executes Google OAuth 2.0 Web Application flow using a local Flask callback server.

    1. Loads client configuration from credentials_path.
    2. Initializes google_auth_oauthlib.flow.Flow with redirect_uri.
    3. Generates authorization URL and captures the exact generated state.
    4. Starts local Flask server on port 5678 listening on /rest/oauth2-credential/callback.
    5. Preserves state across the flow and validates callback using standard OAuthlib mechanisms.
    6. Exchanges the authorization code using the same Flow instance and matching redirect URI.
    7. Returns valid google.oauth2.credentials.Credentials.
    """
    from flask import Flask, request
    from google_auth_oauthlib.flow import Flow
    from werkzeug.serving import make_server

    os.environ["OAUTHLIB_INSECURE_TRANSPORT"] = "1"

    if not os.path.exists(credentials_path):
        raise FileNotFoundError(
            f"OAuth credentials file not found at: {credentials_path}. "
            "Please ensure your Google Cloud OAuth Web Client JSON is saved in secrets/credentials.json."
        )

    # Check if port is already occupied by an active service (e.g. n8n container)
    import urllib.error
    import urllib.request
    try:
        with urllib.request.urlopen(f"http://localhost:{port}/", timeout=1) as resp:
            raise RuntimeError(
                f"Port {port} is already occupied by an active service (HTTP status {resp.status}). "
                f"If you have an n8n Docker container or another service running on port {port}, "
                f"please temporarily stop it (e.g. 'wsl docker stop n8n' or 'docker stop n8n') "
                f"so the Gmail OAuth callback server can bind to http://localhost:{port}/rest/oauth2-credential/callback."
            )
    except urllib.error.HTTPError as he:
        raise RuntimeError(
            f"Port {port} is already occupied by an active service (HTTP error {he.code}). "
            f"If you have an n8n Docker container or another service running on port {port}, "
            f"please temporarily stop it (e.g. 'wsl docker stop n8n' or 'docker stop n8n') "
            f"so the Gmail OAuth callback server can bind to http://localhost:{port}/rest/oauth2-credential/callback."
        )
    except (urllib.error.URLError, ConnectionRefusedError, TimeoutError, OSError):
        # Port is free for our server
        pass

    # 1. Initialize Flow with redirect_uri
    flow = Flow.from_client_secrets_file(
        credentials_path,
        scopes=SCOPES,
        redirect_uri=redirect_uri,
    )

    # 2. Generate authorization URL and capture the exact state value generated by OAuthlib
    auth_url, state = flow.authorization_url(
        access_type="offline",
        include_granted_scopes="true",
        prompt="consent",
    )

    logger.info("Generated OAuth authorization URL.")

    app = Flask("gmail_oauth_callback")
    app.logger.disabled = True
    logging.getLogger("werkzeug").setLevel(logging.ERROR)

    auth_completed = threading.Event()
    callback_error: List[str] = []

    @app.route("/rest/oauth2-credential/callback")
    def oauth_callback():
        error = request.args.get("error")
        callback_state = request.args.get("state")

        state_matches = (callback_state == state) if callback_state else False

        logger.info("OAuth callback received. Validating request parameters...")

        if error:
            error_desc = request.args.get("error_description", "")
            err_msg = f"OAuth Authorization Error from Google: {error} ({error_desc})"
            logger.error("%s", err_msg)
            callback_error.append(err_msg)
            auth_completed.set()
            return f"<html><body><h3>Authentication Failed</h3><p>{err_msg}</p></body></html>", 400

        if not callback_state:
            err_msg = "OAuth Error: Missing state parameter in callback request"
            logger.error("%s", err_msg)
            callback_error.append(err_msg)
            auth_completed.set()
            return f"<html><body><h3>Authentication Failed</h3><p>{err_msg}</p></body></html>", 400

        if not state_matches:
            err_msg = "OAuth Error: State parameter mismatch between request and callback"
            logger.error("%s", err_msg)
            callback_error.append(err_msg)
            auth_completed.set()
            return f"<html><body><h3>Authentication Failed</h3><p>{err_msg}</p></body></html>", 400

        try:
            # Use the same Flow instance to exchange code for tokens
            # Standard google-auth-oauthlib / oauthlib mechanism
            flow.fetch_token(authorization_response=request.url)
            auth_completed.set()
            logger.info("OAuth token successfully exchanged using Flow.fetch_token.")
            return (
                "<html><body style='font-family: sans-serif; text-align: center; padding: 40px;'>"
                "<h2 style='color: #2e7d32;'>Authentication Successful!</h2>"
                "<p>Your RVCE Gmail credentials have been verified.</p>"
                "<p>You can close this tab and return to your terminal.</p>"
                "</body></html>"
            )
        except Exception as exc:
            tb = traceback.format_exc()
            logger.error("Exception during Flow.fetch_token(): %s\n%s", exc, tb)
            err_msg = f"OAuth Token Exchange Error: {type(exc).__name__}: {exc}"
            callback_error.append(err_msg)
            auth_completed.set()
            return f"<html><body><h3>Authentication Failed</h3><p>{err_msg}</p></body></html>", 400

    server = make_server("localhost", port, app)
    server_thread = threading.Thread(target=server.serve_forever, daemon=True)
    server_thread.start()

    logger.info("Local OAuth callback server listening on http://localhost:%d/rest/oauth2-credential/callback", port)
    logger.info("Opening browser for authorization. If browser does not open automatically, visit:")
    logger.info("%s", auth_url)

    try:
        webbrowser.open(auth_url)
    except Exception as e:
        logger.warning("Could not launch browser automatically: %s", e)

    # Wait for callback or timeout
    finished = auth_completed.wait(timeout=timeout_seconds)
    server.shutdown()

    if not finished:
        raise TimeoutError(f"OAuth authorization timed out after {timeout_seconds} seconds waiting on {redirect_uri}.")

    if callback_error:
        raise RuntimeError(f"OAuth authorization failed: {callback_error[0]}")

    return flow.credentials


def get_gmail_service(
    credentials_path: str = "secrets/credentials.json",
    token_path: str = "secrets/token.json",
    redirect_uri: str = REDIRECT_URI,
    port: int = 5678,
    allow_interactive_oauth: bool = True,
) -> Any:
    """
    Authenticate and return an authorized Gmail API service instance.
    Uses cached token if valid, refreshes if expired, or triggers
    local Flask OAuth callback on port 5678 when allow_interactive_oauth is True.
    """
    from google.auth.transport.requests import Request
    from google.oauth2.credentials import Credentials
    from googleapiclient.discovery import build

    creds = None

    # 1. Load cached token if available
    if os.path.exists(token_path):
        try:
            creds = Credentials.from_authorized_user_file(token_path, SCOPES)
            if creds and creds.valid:
                logger.info("Loaded valid cached Gmail OAuth token from %s", token_path)
        except Exception as e:
            logger.warning("Could not load cached token from %s: %s", token_path, type(e).__name__)
            creds = None

    # 2. Refresh or trigger browser login if needed
    if not creds or not creds.valid:
        if creds and creds.expired and creds.refresh_token:
            logger.info("Refreshing expired Gmail OAuth token...")
            try:
                creds.refresh(Request())
            except Exception as e:
                logger.warning("Token refresh failed (%s).", type(e).__name__)
                creds = None

        if not creds or not creds.valid:
            if not allow_interactive_oauth:
                raise RuntimeError(
                    "Non-interactive Gmail authentication failed: valid or refreshable token is required."
                )
            creds = run_flask_oauth_flow(
                credentials_path=credentials_path,
                redirect_uri=redirect_uri,
                port=port,
            )

        # 3. Save new/refreshed token to disk
        os.makedirs(os.path.dirname(token_path) or ".", exist_ok=True)
        with open(token_path, "w", encoding="utf-8") as token_file:
            token_file.write(creds.to_json())
        logger.info("Saved refreshed Gmail OAuth token to %s", token_path)

    # 4. Build and return service
    service = build("gmail", "v1", credentials=creds, cache_discovery=False)
    return service


def fetch_message_ids(
    service: Any,
    query: str,
    max_results: int = 50,
    page_token: Optional[str] = None,
    raise_on_error: bool = False,
) -> Tuple[List[str], Optional[str]]:
    """
    Fetch a page of Gmail message IDs matching a search query.

    Returns:
        (message_ids, next_page_token)
    """
    try:
        response = (
            service.users()
            .messages()
            .list(
                userId="me",
                q=query,
                maxResults=max_results,
                pageToken=page_token,
                includeSpamTrash=False,
            )
            .execute()
        )
        messages = response.get("messages", [])
        msg_ids = [m["id"] for m in messages if "id" in m]
        next_page = response.get("nextPageToken")
        return msg_ids, next_page
    except Exception as e:
        logger.error("Error fetching message IDs (%s)", type(e).__name__)
        if raise_on_error:
            raise
        return [], None


def fetch_message_full(service: Any, message_id: str) -> Optional[Dict[str, Any]]:
    """
    Fetch complete message details including headers, MIME parts, and body.
    """
    try:
        msg = (
            service.users()
            .messages()
            .get(userId="me", id=message_id, format="full")
            .execute()
        )
        return msg
    except Exception as e:
        logger.error("Error fetching message %s: %s", message_id, e)
        return None


def fetch_attachment_bytes(
    service: Any,
    message_id: str,
    attachment_id: str,
) -> Optional[bytes]:
    """
    Download and decode an attachment's raw byte payload from Gmail API.
    """
    import base64

    try:
        att = (
            service.users()
            .messages()
            .attachments()
            .get(userId="me", messageId=message_id, id=attachment_id)
            .execute()
        )
        data = att.get("data", "")
        if not data:
            return None
        # Gmail uses base64url encoding
        return base64.urlsafe_b64decode(data)
    except Exception as e:
        logger.error("Error fetching attachment %s for message %s: %s", attachment_id, message_id, e)
        return None
